/**
 * Convert paise (1 INR = 100 paise) to AUSD units (6 decimals)
 * Benchmark conversion rate: 1 USD ~ 83.33 INR => 1 AUSD ~ 8333 paise.
 * For exact integer arithmetic:
 * AUSD (micro-units, 6 decimals) = (paise * 1_000_000 + 4166) / 8333
 */
export function paiseToAusdMicroUnits(paise: number): bigint {
  const p = BigInt(Math.max(0, Math.trunc(paise)));
  return (p * 1_000_000n + 4166n) / 8333n;
}

export function formatAusdAmount(microUnits: bigint): string {
  const whole = microUnits / 1_000_000n;
  const fraction = (microUnits % 1_000_000n).toString().padStart(6, '0').slice(0, 2);
  return `${whole}.${fraction} AUSD`;
}
